/** Получить все новости с сортировкой по дате (от свежих к старым) */
export function getAllNews(): NewsArticle[] {
  return [...newsArticles].sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
}

/** Получить новость по ее slug */
export function getNewsBySlug(slug: string): NewsArticle | undefined {
  return newsArticles.find((item) => item.slug === slug);
}

/** Получить связанные новости для блока «Читайте также» */
export function getRelatedNews(currentSlug: string, limit = 3): NewsArticle[] {
  return getAllNews()
    .filter((item) => item.slug !== currentSlug)
    .slice(0, limit);
}
